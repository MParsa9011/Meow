        }
        AppLanguage.EN -> engine.displayName
    }

    fun engineAccuracy(engine: ModelEngineType): String = when (language) {
        AppLanguage.FA -> when (engine) {
            ModelEngineType.HYBRID -> "دقت ۷۹.۴٪"
            ModelEngineType.ACOUSTIC -> "دقت ۷۴.۶٪"
            ModelEngineType.CNN -> "دقت ۷۶.۲٪"
        }
        AppLanguage.EN -> engine.accuracyLabel
    }

    fun engineSubtitle(engine: ModelEngineType): String = when (language) {
        AppLanguage.FA -> when (engine) {
            ModelEngineType.HYBRID -> "ترکیب ۲۳۴ ویژگی زیستی-آکوستیک (۴۵٪) و شبکه عصبی مل-اسپکتروگرام (۵۵٪)"
            ModelEngineType.ACOUSTIC -> "استخراج زیروبمی YIN، ضرایب MFCC، شار طیفی و طبقه‌بندی لجستیک"
            ModelEngineType.CNN -> "شبکه کانولوشنی دو‌بعدی بر روی طیف مل ۱۲۸ بانده"
        }
        AppLanguage.EN -> engine.subtitle
    }

    fun engineShortChip(engine: ModelEngineType): String = when (language) {
        AppLanguage.FA -> when (engine) {
            ModelEngineType.HYBRID -> "هوش ترکیبی • ۷۹.۴٪"
            ModelEngineType.ACOUSTIC -> "زیست‌آکوستیک • ۷۴.۶٪"
            ModelEngineType.CNN -> "اسپکتروگرام • ۷۶.۲٪"
        }
        AppLanguage.EN -> when (engine) {
            ModelEngineType.HYBRID -> "Hybrid AI • 79.4%"
            ModelEngineType.ACOUSTIC -> "Bioacoustic • 74.6%"
            ModelEngineType.CNN -> "Mel CNN • 76.2%"
        }
    }

    fun sampleShortLabel(sampleId: String, fallback: String): String = when (language) {
        AppLanguage.FA -> when (sampleId) {
            "food_sample" -> "میو گرسنگی"
            "brushing_sample" -> "خرخر شادی"
            "isolation_sample" -> "صدای دلتنگی"
            else -> fallback
        }
        AppLanguage.EN -> fallback
    }

    fun intentBadge(rank: Int): String = when (language) {
        AppLanguage.FA -> when (rank) {
            1 -> "بالاترین تطابق"
            2 -> "تطابق دوم"
            else -> "احتمال کمتر"
        }
        AppLanguage.EN -> when (rank) {
            1 -> "Highest match"
            2 -> "Second match"
            else -> "Low match"
        }
    }

    fun intentTagLabel(code: IntentCode): String = when (language) {
        AppLanguage.FA -> when (code) {
            IntentCode.FOOD -> "گرسنگی"
            IntentCode.BRUSHING -> "نوازش و توجه"
            IntentCode.ISOLATION -> "نیاز به مراقبت"
        }
        AppLanguage.EN -> when (code) {
            IntentCode.FOOD -> "Hunger"
            IntentCode.BRUSHING -> "Affection"
            IntentCode.ISOLATION -> "Needs Care"
        }
    }

    fun intentTagLabelFromCodeString(codeStr: String): String =
        intentTagLabel(IntentCode.fromCode(codeStr))
}

